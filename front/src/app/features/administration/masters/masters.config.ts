/** Master registry (mirrors api/config/masters.config.js) — drives the generic UI + validation. */
export type FieldType = 'code' | 'text' | 'phone' | 'email' | 'int' | 'decimal' | 'date' | 'bool' | 'select';

export interface FieldRef {
  master: string;   // which master to load options from (/api/masters/<master>)
  valueCol: string; // option value column
  labelCol: string; // option label column
}

export interface MasterField {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  placeholder?: string;
  ref?: FieldRef;
  auto?: boolean; // code auto-generated by server (read-only in the form)
}

export interface MasterConfig {
  title: string;
  pk: string;
  fields: MasterField[];
}

const C = (name: string, label: string, ph = 'e.g. CODE01'): MasterField => ({ name, label, type: 'code', required: true, placeholder: ph });
const AC = (name: string, label: string): MasterField => ({ name, label, type: 'code', auto: true, placeholder: 'Auto-generated on save' });
const T = (name: string, label: string, required = false): MasterField => ({ name, label, type: 'text', required, placeholder: 'Enter ' + label.toLowerCase() });
const I = (name: string, label: string, required = false): MasterField => ({ name, label, type: 'int', required, placeholder: '0' });
const D = (name: string, label: string, required = false): MasterField => ({ name, label, type: 'decimal', required, placeholder: '0.00' });
const EMAIL = (name = 'email'): MasterField => ({ name, label: 'Email', type: 'email', placeholder: 'name@example.com' });
const PHONE = (name = 'phone'): MasterField => ({ name, label: 'Phone', type: 'phone', placeholder: '+44 7123 456789' });
const DATE = (name: string, label: string): MasterField => ({ name, label, type: 'date', placeholder: '' });
const SELECT = (name: string, label: string, ref: FieldRef, required = false): MasterField => ({ name, label, type: 'select', required, placeholder: 'Select ' + label.toLowerCase(), ref });

