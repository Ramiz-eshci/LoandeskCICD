/** Shared validation regexes (mirror the server). */
export const VALIDATION = {
  name: /^[A-Za-z][A-Za-z .'\-]*$/,
  code: /^[A-Za-z0-9_-]+$/,
  text: /^[A-Za-z0-9 .,&/'()\-]+$/,
  phone: /^[0-9+()\-\s]+$/,
  int: /^-?\d+$/,
  decimal: /^-?\d+(\.\d+)?$/,
};

